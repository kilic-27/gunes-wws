-- 4) Zuordnung: erstes Stück je Typ übernimmt den Typ-Artikel, die anderen bekommen einen neuen Artikel
create temp table ziel as
select s.uid, s.name, t.id as typ_id,
       row_number() over (partition by s.typ_barcode order by s.uid::bigint) as rn
from src s join artikel t on t.barcode = s.typ_barcode;
alter table ziel add column ziel_id uuid;
update ziel set ziel_id = case when rn = 1 then typ_id else gen_random_uuid() end;

insert into artikel (id, name, typ, beschreibung, preis, tagespreis, vpe, gewerk_id, standard_lager_id, meldebestand, foto_url, aktiv, erstellt_am)
select z.ziel_id, z.name, t.typ, t.beschreibung, t.preis, t.tagespreis, t.vpe, t.gewerk_id, t.standard_lager_id, t.meldebestand, t.foto_url, t.aktiv, t.erstellt_am
from ziel z join artikel t on t.id = z.typ_id
where z.rn > 1;

update artikel a set name = z.name from ziel z where z.rn = 1 and a.id = z.ziel_id;

-- 5) Stücke auf ihren Artikel setzen, fehlende Stücke anlegen
update bestand_stueck s set artikel_id = z.ziel_id
from ziel z where s.barcode = 'UID' || z.uid;

insert into bestand_stueck (artikel_id, barcode, lager_id, status)
select z.ziel_id, 'UID' || z.uid, coalesce(t.standard_lager_id, '6369ae8c-e23a-4e3c-9c07-78f659dae500'::uuid), 'verfuegbar'
from ziel z join artikel t on t.id = z.ziel_id
where not exists (select 1 from bestand_stueck s where s.barcode = 'UID' || z.uid);

-- 6) Lieferschein-Positionen von Stücken zeigen auf den Artikel des Stücks
update lieferschein_positionen p set artikel_id = s.artikel_id
from bestand_stueck s
where p.bestand_stueck_id = s.id and p.art = 'stueck' and p.artikel_id is distinct from s.artikel_id;

