  (select count(*) from bestand_stueck) as stuecke,
  (select count(*) from bestand_stueck s where exists (select 1 from ziel z where s.barcode = 'UID' || z.uid)) as stuecke_aus_altsystem,
  (select count(*) from artikel a where a.typ = 'werkzeug' and not exists (select 1 from bestand_stueck s where s.artikel_id = a.id)) as werkzeug_ohne_stueck,
  (select count(*) from bestand_stueck where status = 'verliehen') as verliehen;

-- Werkzeug-Artikel ohne Stück (nicht aus dem Artikelbestand, ggf. selbst angelegt oder Test)
select a.name, a.barcode from artikel a
where a.typ = 'werkzeug' and not exists (select 1 from bestand_stueck s where s.artikel_id = a.id)
order by a.name;
